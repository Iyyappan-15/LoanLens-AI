"""
LoanLens AI - Anti-Hallucination Evidence Citation Validator
Validates whether citations generated by AI modules (document_id, transaction_id, etc.)
actually exist in the ground truth case repository.
"""
from typing import List, Dict, Any, Tuple
from pydantic import BaseModel
from backend.app.schemas.shared import FindingSchema, EvidenceReference

class CitationValidationResult(BaseModel):
    is_valid: bool
    verified_citations: List[EvidenceReference]
    invalid_citations: List[EvidenceReference]
    rejection_reasons: List[str]

class EvidenceValidator:
    """
    Enforces strict citation integrity.
    Rejects or flags findings that hallucinate non-existent documents or transactions.
    """

    @staticmethod
    def validate_citations(
        evidence_list: List[EvidenceReference],
        available_documents: List[str],
        available_transaction_ids: List[str],
    ) -> CitationValidationResult:
        verified = []
        invalid = []
        reasons = []

        for ref in evidence_list:
            # 1. Document Existence Check
            if ref.document_id not in available_documents:
                invalid.append(ref)
                reasons.append(
                    f"Hallucination detected: document_id '{ref.document_id}' does not exist in case repository."
                )
                continue

            # 2. Transaction Existence Check (if transaction-level citation)
            if ref.transaction_id and ref.transaction_id not in available_transaction_ids:
                invalid.append(ref)
                reasons.append(
                    f"Hallucination detected: transaction_id '{ref.transaction_id}' not found in document '{ref.document_id}'."
                )
                continue

            verified.append(ref)

        is_all_valid = len(invalid) == 0 and len(verified) > 0
        return CitationValidationResult(
            is_valid=is_all_valid,
            verified_citations=verified,
            invalid_citations=invalid,
            rejection_reasons=reasons,
        )

    @staticmethod
    def verify_and_stamp_finding(
        finding: FindingSchema,
        available_documents: List[str],
        available_transaction_ids: List[str],
    ) -> FindingSchema:
        """
        Validates the finding's citations and updates its `is_verified` flag.
        If citations fail, adds an audit notice to the description.
        """
        val_result = EvidenceValidator.validate_citations(
            finding.evidence,
            available_documents,
            available_transaction_ids,
        )

        if val_result.is_valid:
            finding.is_verified = True
        else:
            finding.is_verified = False
            finding.description += f" [UNVERIFIED CITATIONS: {'; '.join(val_result.rejection_reasons)}]"

        return finding
